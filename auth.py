"""Accounts: password hashing, login sessions, invite codes and first-admin setup.

Registration always needs a code: the one-time setup code printed at startup while no account
exists (it creates the first admin, who takes over study records made before accounts existed),
or an invite code generated by an admin.

Command line, e.g. inside the container:
    python auth.py create-user NAME [--admin]
    python auth.py reset-password NAME
"""
from __future__ import annotations

import argparse
import getpass
import hashlib
import hmac
import os
import re
import secrets
import sys
import threading
import time
from datetime import datetime, timedelta, timezone

from database import connect, initialize

TZ = timezone(timedelta(hours=8))
COOKIE = 'finreg_session'
SESSION_DAYS = 30
INVITE_DAYS = 7
PASSWORD_MIN, PASSWORD_MAX = 8, 128
USERNAME = re.compile(r'[\w.-]{2,32}')  # \w also matches Chinese characters
CODE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'  # no 0/O, 1/I/L
SCRYPT = {'n': 2 ** 14, 'r': 8, 'p': 1}
MAX_FAILURES, LOCK_SECONDS = 8, 15 * 60
ROLES = ('admin', 'user')

_lock = threading.Lock()
_failures = {}        # lower-case username -> (failed attempts, monotonic time of the first)
_setup = {'code': None}
_dummy_hash = []


def stamp(delta=timedelta()):
    return (datetime.now(TZ) + delta).isoformat(timespec='seconds')


# ---------------------------------------------------------------- passwords and codes

def hash_password(password):
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, dklen=32, **SCRYPT)
    return f"scrypt${SCRYPT['n']}${SCRYPT['r']}${SCRYPT['p']}${salt.hex()}${digest.hex()}"


def verify_password(password, stored):
    try:
        _, n, r, p, salt, digest = stored.split('$')
        actual = hashlib.scrypt(str(password).encode(), salt=bytes.fromhex(salt), n=int(n), r=int(r),
                                p=int(p), dklen=len(digest) // 2)
    except (ValueError, TypeError, AttributeError):
        return False
    return hmac.compare_digest(actual.hex(), digest)


def _dummy():
    # Unknown usernames still cost one hash, so response time does not reveal which names exist.
    if not _dummy_hash:
        _dummy_hash.append(hash_password(secrets.token_hex(8)))
    return _dummy_hash[0]


def new_code():
    return ''.join(secrets.choice(CODE_ALPHABET) for _ in range(12))


def normalize_code(code):
    return re.sub(r'[^0-9A-Z]', '', str(code or '').upper())


def format_code(code):
    """Generated 12-character codes read as XXXX-XXXX-XXXX; others (e.g. from the environment) as is."""
    if len(code) != 12:
        return code
    return '-'.join(code[i:i + 4] for i in range(0, 12, 4))


def _digest(token):
    return hashlib.sha256(token.encode()).hexdigest()


def check_username(name):
    name = str(name or '').strip()
    if not USERNAME.fullmatch(name):
        raise ValueError('用户名需为2–32个字符，可使用中文、字母、数字、点、横线和下划线')
    return name


def check_password(password):
    if not isinstance(password, str) or not PASSWORD_MIN <= len(password) <= PASSWORD_MAX:
        raise ValueError(f'密码长度需为{PASSWORD_MIN}–{PASSWORD_MAX}位')
    return password


def _reject(message):
    time.sleep(0.4)  # slows down guessing; ThreadingHTTPServer only blocks this request
    raise ValueError(message)


# ---------------------------------------------------------------- accounts

def has_users():
    with connect() as c:
        return c.execute('SELECT 1 FROM users LIMIT 1').fetchone() is not None


def setup_code():
    """The code that creates the first admin, or None once any account exists."""
    if has_users():
        return None
    if not _setup['code']:
        _setup['code'] = normalize_code(os.environ.get('FINREG_SETUP_CODE')) or new_code()
    return _setup['code']


def _insert_user(conn, username, password, admin=False):
    username = check_username(username)
    check_password(password)
    if conn.execute('SELECT 1 FROM users WHERE username=?', (username,)).fetchone():
        raise ValueError('用户名已被使用')
    first = conn.execute('SELECT 1 FROM users LIMIT 1').fetchone() is None
    uid = conn.execute('INSERT INTO users(username,password_hash,role,created_at) VALUES(?,?,?,?)',
                       (username, hash_password(password), 'admin' if admin or first else 'user',
                        stamp())).lastrowid
    if first:
        # Records made while the app had no accounts belong to its owner, the first admin.
        for table in ('sessions', 'attempts', 'marks'):
            conn.execute(f'UPDATE {table} SET user_id=? WHERE user_id IS NULL', (uid,))
    return uid


def create_user(username, password, admin=False):
    with connect() as c:
        c.execute('BEGIN IMMEDIATE')
        return _insert_user(c, username, password, admin)


def register(data):
    """Create an account from a setup or invite code. Returns the new user id."""
    username, password = check_username(data.get('username')), check_password(data.get('password'))
    code = normalize_code(data.get('code'))
    expected_setup = setup_code()
    with connect() as c:
        c.execute('BEGIN IMMEDIATE')
        if expected_setup and not c.execute('SELECT 1 FROM users LIMIT 1').fetchone():
            if not hmac.compare_digest(code, expected_setup):
                _reject('初始化码不正确，请查看服务启动日志')
            uid = _insert_user(c, username, password, admin=True)
            _setup['code'] = None
            return uid
        invite = c.execute('SELECT code FROM invites WHERE code=? AND used_by IS NULL AND revoked=0 '
                           'AND expires_at>?', (code, stamp())).fetchone()
        if not invite:
            _reject('邀请码无效、已使用或已过期，请向管理员索取新的邀请码')
        uid = _insert_user(c, username, password)
        c.execute('UPDATE invites SET used_by=?, used_at=? WHERE code=?', (uid, stamp(), code))
        return uid


def login(username, password):
    """Check credentials and return the user id; repeated failures lock the name for a while."""
    name = str(username or '').strip()
    key = name.lower()
    with _lock:
        count, since = _failures.get(key, (0, 0.0))
        if count >= MAX_FAILURES and time.monotonic() - since < LOCK_SECONDS:
            raise ValueError(f'登录失败次数过多，请{LOCK_SECONDS // 60}分钟后再试')
    with connect() as c:
        row = c.execute('SELECT id, password_hash, disabled FROM users WHERE username=?', (name,)).fetchone()
    if not verify_password(str(password or ''), row['password_hash'] if row else _dummy()):
        with _lock:
            count, since = _failures.get(key, (0, 0.0))
            if time.monotonic() - since >= LOCK_SECONDS:
                count, since = 0, time.monotonic()
            _failures[key] = (count + 1, since)
        _reject('用户名或密码错误')
    with _lock:
        _failures.pop(key, None)
    if row['disabled']:
        raise ValueError('账号已停用，请联系管理员')
    return row['id']


# ---------------------------------------------------------------- login sessions

def start_session(uid):
    token = secrets.token_urlsafe(32)
    with connect() as c:
        c.execute('DELETE FROM auth_sessions WHERE expires_at<=?', (stamp(),))
        c.execute('INSERT INTO auth_sessions(token_hash,user_id,created_at,expires_at) VALUES(?,?,?,?)',
                  (_digest(token), uid, stamp(), stamp(timedelta(days=SESSION_DAYS))))
        c.execute('UPDATE users SET last_login=? WHERE id=?', (stamp(), uid))
    return token


def session_user(token):
    """The signed-in user for a cookie token, or None (unknown, expired or disabled)."""
    if not token:
        return None
    with connect() as c:
        row = c.execute('''SELECT u.id, u.username, u.role FROM auth_sessions s JOIN users u ON u.id=s.user_id
            WHERE s.token_hash=? AND s.expires_at>? AND u.disabled=0''', (_digest(token), stamp())).fetchone()
    return dict(row) if row else None


def end_session(token):
    if token:
        with connect() as c:
            c.execute('DELETE FROM auth_sessions WHERE token_hash=?', (_digest(token),))


def change_password(uid, token, data):
    """Change one's own password; other devices are signed out, this one stays."""
    with connect() as c:
        row = c.execute('SELECT password_hash FROM users WHERE id=?', (uid,)).fetchone()
    if not verify_password(str(data.get('current') or ''), row['password_hash']):
        _reject('当前密码不正确')
    password = check_password(data.get('password'))
    with connect() as c:
        c.execute('UPDATE users SET password_hash=? WHERE id=?', (hash_password(password), uid))
        c.execute('DELETE FROM auth_sessions WHERE user_id=? AND token_hash!=?', (uid, _digest(token or '')))
    return {'saved': True}


# ---------------------------------------------------------------- administration

def overview():
    with connect() as c:
        users = [dict(r) for r in c.execute('''SELECT id, username, role, disabled, created_at, last_login,
            (SELECT count(*) FROM attempts a WHERE a.user_id=users.id) answers
            FROM users ORDER BY id''')]
        invites = [dict(r) for r in c.execute('''SELECT i.code, i.created_at, i.expires_at, i.used_at,
            i.revoked, u.username used_by FROM invites i LEFT JOIN users u ON u.id=i.used_by
            ORDER BY i.created_at DESC LIMIT 50''')]
    now = stamp()
    for invite in invites:
        invite['status'] = ('used' if invite['used_by'] else 'revoked' if invite['revoked']
                            else 'expired' if invite['expires_at'] <= now else 'open')
        invite['code'] = format_code(invite['code'])
    return {'users': users, 'invites': invites}


def create_invite(admin_uid):
    code = new_code()
    with connect() as c:
        c.execute('INSERT INTO invites(code,created_by,created_at,expires_at) VALUES(?,?,?,?)',
                  (code, admin_uid, stamp(), stamp(timedelta(days=INVITE_DAYS))))
    return {'code': format_code(code), 'days': INVITE_DAYS}


def revoke_invite(code):
    with connect() as c:
        c.execute('UPDATE invites SET revoked=1 WHERE code=? AND used_by IS NULL', (normalize_code(code),))
    return {'revoked': True}


def update_user(admin_uid, uid, data):
    """Admin changes to another account: password reset, role, enabled state."""
    if uid == admin_uid and ('role' in data or 'disabled' in data):
        raise ValueError('不能停用自己或修改自己的角色')
    with connect() as c:
        c.execute('BEGIN IMMEDIATE')
        if not c.execute('SELECT 1 FROM users WHERE id=?', (uid,)).fetchone():
            raise ValueError('用户不存在')
        signout = False
        if 'password' in data:
            c.execute('UPDATE users SET password_hash=? WHERE id=?',
                      (hash_password(check_password(data['password'])), uid))
            signout = True
        if 'role' in data:
            if data['role'] not in ROLES:
                raise ValueError('无效角色')
            c.execute('UPDATE users SET role=? WHERE id=?', (data['role'], uid))
        if 'disabled' in data:
            c.execute('UPDATE users SET disabled=? WHERE id=?', (int(bool(data['disabled'])), uid))
            signout = signout or bool(data['disabled'])
        if signout:
            c.execute('DELETE FROM auth_sessions WHERE user_id=?', (uid,))
    return {'saved': True}


# ---------------------------------------------------------------- command line

def _ask_password():
    password = getpass.getpass('新密码：')
    if password != getpass.getpass('再次输入：'):
        sys.exit('两次输入的密码不一致')
    return check_password(password)


def main(argv=None):
    parser = argparse.ArgumentParser(description='知序账号维护')
    commands = parser.add_subparsers(dest='command', required=True)
    create = commands.add_parser('create-user', help='创建账号（第一个账号自动成为管理员）')
    create.add_argument('username')
    create.add_argument('--admin', action='store_true', help='设为管理员')
    reset = commands.add_parser('reset-password', help='重置密码并解除停用')
    reset.add_argument('username')
    args = parser.parse_args(argv)
    initialize()
    try:
        if args.command == 'create-user':
            create_user(args.username, _ask_password(), args.admin)
            print(f'已创建账号 {args.username}')
        else:
            with connect() as c:
                row = c.execute('SELECT id FROM users WHERE username=?', (args.username.strip(),)).fetchone()
            if not row:
                sys.exit('用户不存在')
            password = _ask_password()
            with connect() as c:
                c.execute('UPDATE users SET password_hash=?, disabled=0 WHERE id=?', (hash_password(password), row['id']))
                c.execute('DELETE FROM auth_sessions WHERE user_id=?', (row['id'],))
            print(f'已重置 {args.username} 的密码，原有登录已失效')
    except ValueError as e:
        sys.exit(str(e))


if __name__ == '__main__':
    main()
